"""Build the two hand-run SQL files from the migrations (D-139), so they never drift from them:

    Solution/db/sql/create-database.sql    an EMPTY database -> the current schema (0001..latest)
    Solution/db/sql/upgrade-from-0013.sql  a database of the previous version (last 0013_inbox)
                                           -> the current schema (0014..latest)

    node scripts/py.mjs -m scripts.build_sql [runtime-role]     (npm run db:sql)

Both run in one transaction, connected as the OWNER role (DATABASE_OWNER_URL), and record each
migration in `schema_migration` - the new app then finds nothing to do and starts normally.
Table rights go to the runtime role (the DATABASE_URL user): `app_rw` unless one is given.
"""

import sys
from pathlib import Path

from app.db.migrate import for_role, read_sql

OUT = Path(__file__).resolve().parents[2] / "db" / "sql"
VERSIONS = Path(__file__).resolve().parents[1] / "alembic" / "versions"
PREVIOUS = "0013_inbox"  # the last migration of the previous (Node) version


def revisions() -> list[str]:
    return sorted(p.stem for p in VERSIONS.glob("[0-9][0-9][0-9][0-9]_*.py"))


def body(revs: list[str], role: str) -> str:
    parts = []
    for rev in revs:
        parts.append(f"-- ===== {rev} =====\n{for_role(read_sql(rev, 'up'), role).strip()}\n")
        # Revision ids come from our own migration file names, never from input.
        record = "INSERT INTO schema_migration (id) VALUES ('{}') ON CONFLICT DO NOTHING;\n"
        parts.append(record.format(rev))
    return "\n".join(parts)


def header(title: str, what: str, role: str, latest: str) -> str:
    return f"""-- {title}
-- Generated by `npm run db:sql` from Solution/backend-py/alembic/sql - do not edit by hand.
--
-- {what}
-- Ends at {latest}. Run it ONCE, connected as the database OWNER role (the user in
-- DATABASE_OWNER_URL), e.g.  psql "<owner connection string>" -f <this file>
-- or paste it into pgAdmin / the Azure portal query editor. It is one transaction: any error
-- leaves the database untouched.
--
-- Table rights are granted to the runtime role "{role}" (the user in DATABASE_URL). If yours
-- is different, regenerate with `npm run db:sql -- <role>` (or replace every "{role}").
-- Both roles must exist first (CREATE ROLE ... LOGIN; Solution/db/init/001_roles_and_template.sql
-- or Solution/docs/azure-code-deploy.md section 2), or the GRANTs fail and nothing changes.
-- Afterwards start the new app as usual: it sees every migration recorded and changes nothing.

"""


def main() -> None:
    role = sys.argv[1] if len(sys.argv) > 1 else "app_rw"
    revs = revisions()
    latest = revs[-1]
    OUT.mkdir(parents=True, exist_ok=True)

    create = (
        header(
            "Kanban - create the database schema from empty",
            "For a NEW, EMPTY database (no tables yet).",
            role,
            latest,
        )
        + "BEGIN;\n\n"
        + body(revs, role)
        + "\nCOMMIT;\n"
    )
    newer = revs[revs.index(PREVIOUS) + 1 :]
    # PREVIOUS is a constant above, not input.
    guard = f"""DO $$
BEGIN
  IF to_regclass('public.schema_migration') IS NULL THEN
    RAISE EXCEPTION 'Not a Kanban database (no schema_migration). Use create-database.sql.';
  END IF;
  IF to_regclass('public.alembic_version') IS NOT NULL THEN
    RAISE EXCEPTION 'Already managed by the new version (alembic_version exists).';
  END IF;
  IF (SELECT max(id) FROM schema_migration) <> '{PREVIOUS}' THEN
    RAISE EXCEPTION 'Expected the previous version (last {PREVIOUS}), found %.',
      (SELECT max(id) FROM schema_migration);
  END IF;
END $$;
"""  # noqa: S608
    upgrade = (
        header(
            "Kanban - upgrade a database of the previous version to the current schema",
            f"For an EXISTING database whose last migration is {PREVIOUS} (the previous version). "
            "Keeps all data;\n-- cards in Testing (or UAT) end in UAT, with history entries. "
            "Take a backup first.",
            role,
            latest,
        )
        + "BEGIN;\n\n"
        + guard
        + "\n"
        + body(newer, role)
        + "\nCOMMIT;\n"
    )
    (OUT / "create-database.sql").write_text(create, encoding="utf-8", newline="\n")
    (OUT / f"upgrade-from-{PREVIOUS[:4]}.sql").write_text(upgrade, encoding="utf-8", newline="\n")
    print(f"wrote {OUT / 'create-database.sql'} ({len(revs)} migrations)")
    print(f"wrote {OUT / f'upgrade-from-{PREVIOUS[:4]}.sql'} ({', '.join(newer)})")
    print(f"runtime role: {role}")


if __name__ == "__main__":
    main()
